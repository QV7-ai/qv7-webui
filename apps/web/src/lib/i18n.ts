export function t(lang: UiLang, key: keyof typeof COPY.en, vars?: Record<string, string | number>) {
  const text = COPY[lang][key] || COPY.en[key];
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function fieldLabel(lang: UiLang, key: string) {
  return GENERATION_LABELS[key]?.[lang] || GENERATION_LABELS[key]?.en || key;
}

