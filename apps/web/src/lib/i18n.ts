export function applyMotion(enabled: boolean) {
  document.documentElement.dataset.motion = enabled ? "on" : "off";
  window.dispatchEvent(new Event("qv7-motion"));
}

export function applyTheme(theme: string) {
  let mode = theme;
  if (theme === "system") {
    mode = window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
  }
  if (mode !== "light" && mode !== "oled") mode = "dark";
  document.documentElement.dataset.theme = mode;
  paintBrandingTheme(mode);
  const bg = getComputedStyle(document.documentElement).getPropertyValue("--bg").trim();
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta && bg) meta.setAttribute("content", bg);
}

export const DEFAULT_TEXT_SIZE = 100;
export const TEXT_SIZE_MIN = 80;
export const TEXT_SIZE_MAX = 140;
export const TEXT_SIZE_STEP = 5;

export function clampTextSize(value: unknown) {
  const n = Math.round(Number(value) / TEXT_SIZE_STEP) * TEXT_SIZE_STEP;
  if (!Number.isFinite(n)) return DEFAULT_TEXT_SIZE;
  return Math.min(TEXT_SIZE_MAX, Math.max(TEXT_SIZE_MIN, n));
}

export function applyTextSize(size: unknown) {
  const value = clampTextSize(size);
  document.documentElement.style.setProperty("--text-scale", String(value / DEFAULT_TEXT_SIZE));
}

